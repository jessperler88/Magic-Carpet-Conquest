// palette entries 246..254 of pmulti.pal are not used by the book (nor by the hand pointer, sptrs 4): water + 8 wizards
constexpr int kPalWater = 246, kPalWizard = 247;
struct PreviewKey {
    uint32_t seed, size, flags, players, humans;
    uint8_t water, roughness, continent, symmetry;
    bool operator==(const PreviewKey &o) const { return std::memcmp(this, &o, sizeof *this) == 0; }
};
PreviewKey preview_key(const ModeParams &p) {
    PreviewKey k;
    std::memset(&k, 0, sizeof k);
    k.seed = p.seed; k.size = p.world_size; k.flags = p.flags; k.players = (uint32_t)players_of(p); k.humans = p.humans;
    k.water = p.world.water; k.roughness = p.world.roughness; k.continent = p.world.continent; k.symmetry = p.world.symmetry;
    return k;
}
struct {
    bool have = false;
    PreviewKey key{};
    PreviewKey want{};
    uint32_t changed_frame = 0;
    int generations = 0;
    int symmetry = 0, seats = 0;
    uint8_t img[kMapN * kMapN] = {};
    uint8_t land[16] = {};          // height ramp (book palette)
    uint8_t coast = 0, frame_col = 0;
} s_map;

void preview_colours() {
    // land: olive lowland -> tan -> brown hills -> grey rock -> white peaks (the book's own colours)
    static const int ramp[16][3] = {
        {30, 34, 14}, {33, 36, 15}, {36, 38, 17}, {40, 40, 19}, {42, 40, 22}, {44, 40, 26}, {42, 36, 24}, {40, 33, 22},
        {37, 30, 20}, {34, 28, 20}, {36, 32, 26}, {40, 37, 31}, {44, 42, 37}, {50, 48, 43}, {56, 55, 50}, {62, 62, 60},
    };
    const uint8_t *pal = fe_tk_palette();
    for (int i = 0; i < 16; i++) s_map.land[i] = nearest_in(pal, 246, ramp[i][0], ramp[i][1], ramp[i][2]);
    s_map.coast = nearest_in(pal, 246, 16, 12, 8);
    s_map.frame_col = nearest_in(pal, 246, 22, 14, 8);
}

void preview_generate() {
    static LevelData s_tmpl;                        // 0x979c bytes: static, not on the stack
    s_map.key = s_map.want;
    s_map.have = false;
    if (!mode_build_level(fe_tk_game_dir(), s_params, &s_tmpl)) return;
    WorldPreview wp;
    if (!worldgen_preview(s_params, s_tmpl, &wp) || wp.size <= 0) return;
    s_map.generations++;
    s_map.symmetry = wp.symmetry;
    s_map.seats = (int)wp.seats.size();
    const int n = wp.size, cell = n / kMapN;      // cells per minimap pixel (4 .. 32)
    // the minimap is drawn with north (y = 0) at the top, cell (0, 0) at the top left
    for (int py = 0; py < kMapN; py++)
        for (int px = 0; px < kMapN; px++) {
            int water = 0, land = 0, sum = 0;
            for (int y = py * cell; y < (py + 1) * cell; y += std::max(cell / 4, 1))
                for (int x = px * cell; x < (px + 1) * cell; x += std::max(cell / 4, 1)) {
                    const uint8_t h = wp.height[(size_t)y * n + x];
                    if (h) { land++; sum += h; } else water++;
                }
            uint8_t c;
            if (land * 2 <= water) c = kPalWater;
            else {
                const int h = sum / std::max(land, 1);
                c = s_map.land[std::clamp(h * 16 / 0xf0, 0, 15)];
                // the coast line (a third of the pixel in the water: a river crossing it stays land)
                if (water * 3 >= land + water) c = s_map.coast;
            }
            s_map.img[py * kMapN + px] = c;
        }
    // the seats: a 3 x 3 dot in the wizard's colour with a dark rim (empty seats of the symmetry group: a dark dot)
    for (const WorldFeature &f : wp.seats) {
        const int cx = f.x * kMapN / n, cy = f.y * kMapN / n;
        const bool used = f.grade < wp.players;
        for (int dy = -2; dy <= 2; dy++)
            for (int dx = -2; dx <= 2; dx++) {
                const int x = (cx + dx + kMapN) % kMapN, y = (cy + dy + kMapN) % kMapN;
                const bool rim = dx == -2 || dx == 2 || dy == -2 || dy == 2;
                if (used) s_map.img[y * kMapN + x] = rim ? s_map.coast : (uint8_t)(kPalWizard + (f.grade & 7));
                else if (!rim) s_map.img[y * kMapN + x] = s_map.coast;
            }
    }
    s_map.have = true;
}

void preview_update(bool force) {
    if (s_params.seed == 0) return;                     // random: drawn as "?"
    const PreviewKey k = preview_key(s_params);
    if (!(k == s_map.want)) { s_map.want = k; s_map.changed_frame = fe_tk_frame(); }
    if (s_map.have && s_map.want == s_map.key) return;
    // a 2048 world takes ~0.5 s (1024: ~0.15 s): wait for a longer pause in the clicking
    const uint32_t quiet = s_params.world_size > 1024 ? 18 : 6;
    if (force || fe_tk_frame() - s_map.changed_frame >= quiet) preview_generate();
}

void preview_draw() {
    frame_rect(kMapX - 1, kMapY - 1, kMapN + 2, kMapN + 2, s_map.frame_col);
    uint8_t *d = fe_tk_back();
    if (s_params.seed == 0) {                           // a random world: unknown until the match starts
        remap_rect(kMapX, kMapY, kMapN, kMapN, s_shade);
        text_centre(kMapX + kMapN / 2, kMapY + kMapN / 2 - 7, 1, s_map.frame_col, "?");
        return;
    }
    if (!s_map.have) { fill(kMapX, kMapY, kMapN, kMapN, s_map.coast); return; }
    const bool stale = !(s_map.want == s_map.key);
    for (int y = 0; y < kMapN; y++)
        for (int x = 0; x < kMapN; x++) {
            const uint8_t c = s_map.img[y * kMapN + x];
            d[(kMapY + y) * 320 + kMapX + x] = stale ? s_dark[c] : c;    // a new world is on its way
        }
}

