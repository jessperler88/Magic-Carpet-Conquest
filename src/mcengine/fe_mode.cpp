struct Input {
    int x = 0, y = 0;               // pointer (320x200)
    bool left = false, right = false;
    uint8_t key = 0;                // g_key_last (consumed)
};
Input read_input() {
    Input in;
    fe_tk_pointer(&in.x, &in.y);
    const uint8_t ev = fe_tk_events();
    in.left = (ev & 1) != 0;
    in.right = (ev & 0x40) != 0;
    fe_tk_clear_events(0x41);
    in.key = g_key_last;
    g_key_last = 0;
    if (in.key == MC_SC_ENTER) g_key_down[MC_SC_ENTER] = 0;
    if (in.key == MC_SC_ESC) g_key_down[MC_SC_ESC] = 0;
    return in;
}
bool inside(const Input &in, int x0, int x1, int y0, int y1) { return in.x >= x0 && in.x <= x1 && in.y >= y0 && in.y <= y1; }

