uint32_t mix32(uint32_t x) {
    x ^= x >> 16; x *= 0x7feb352du;
    x ^= x >> 15; x *= 0x846ca68bu;
    x ^= x >> 16;
    return x;
}
uint32_t roll_seed() {
    s_roll = mix32(s_roll + fe_tk_now() * 2654435761u + fe_tk_frame() + 0x9e3779b9u);
    return s_roll;
}

