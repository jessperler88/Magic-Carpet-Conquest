uint8_t s_game_pal[768];
bool s_game_pal_ok = false;
void load_game_palette() {
    if (s_game_pal_ok) return;
    char path[1024];
    mc_path_join(path, sizeof path, fe_tk_game_dir(), "data/palette.dat");
    s_game_pal_ok = mc_load_rnc_into(path, s_game_pal, sizeof s_game_pal) == (long)sizeof s_game_pal;
}
// The wizard colour of record `rec` (the HUD's A colour, g_hud_player_colours) as a 6-bit RGB triple.
void wizard_rgb(int rec, int out[3]) {
    load_game_palette();
    const int c = g_hud_player_colours[(rec * 2) & 15];
    for (int k = 0; k < 3; k++) out[k] = s_game_pal_ok ? s_game_pal[c * 3 + k] : 0x20;
}
uint8_t nearest(int r, int g, int b) { return (uint8_t)palette_find_nearest(fe_tk_palette(), r, g, b); }
// nearest among the first `n` entries only (the background's own colours)
uint8_t nearest_in(const uint8_t *pal, int n, int r, int g, int b) {
    int best = 0, bd = 1 << 30;
    for (int i = 0; i < n; i++) {
        const int dr = pal[i * 3] - r, dg = pal[i * 3 + 1] - g, db = pal[i * 3 + 2] - b;
        const int d = dr * dr + dg * dg + db * db;
        if (d < bd) { bd = d; best = i; }
    }
    return (uint8_t)best;
}

