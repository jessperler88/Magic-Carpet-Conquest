const char *end_reason_text(uint32_t r) {
    switch (r) {
    case MATCH_END_ELIMINATION: return "WON BY ELIMINATION";
    case MATCH_END_MANA: return "WON BY MANA DOMINANCE";
    case MATCH_END_TIMER: return "TIME LIMIT: THE MOST CASTLE MANA WON";
    case MATCH_END_DEBUG: return "ENDED BY A DEBUG COMMAND";
    default: return "THE MATCH WAS LEFT BEFORE ITS END";
    }
}

// the seats of the result: records in the match (MODE_PLAYER_IN_MATCH), else the run's humans + bots
int result_seats(int recs[8]) {
    int n = 0;
    for (int i = 0; i < 8; i++) if (s_result.players[i].flags & MODE_PLAYER_IN_MATCH) recs[n++] = i;
    if (n == 0) {
        const int m = players_of(s_result.params);
        for (int i = 0; i < m; i++) recs[n++] = i;
    }
    return n;
}
void seat_name(int rec, char *buf, size_t cap) {
    const ModePlayer &mp = s_result.players[rec];
    const bool bot = (mp.flags & MODE_PLAYER_BOT) || (!(mp.flags & MODE_PLAYER_IN_MATCH) && rec >= (int)s_result.params.humans);
    if (bot) { std::snprintf(buf, cap, "BOT %d", rec); return; }
    if (s_result_names[rec][0]) std::snprintf(buf, cap, "%s", s_result_names[rec]);
    else std::snprintf(buf, cap, "PLAYER %d", rec + 1);
}
bool local_won() {
    return s_result.match_state == MATCH_OVER && s_result.end_reason != MATCH_END_NONE &&
           s_result.players[s_result_local & 7].side == s_result.winner_side;
}

