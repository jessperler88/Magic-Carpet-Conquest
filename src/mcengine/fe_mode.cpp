void fill(int x, int y, int w, int h, uint8_t c) {
    uint8_t *d = fe_tk_back();
    for (int r = std::max(y, 0); r < std::min(y + h, 200); r++)
        for (int k = std::max(x, 0); k < std::min(x + w, 320); k++) d[r * 320 + k] = c;
}
void frame_rect(int x, int y, int w, int h, uint8_t c) {
    fill(x, y, w, 1, c); fill(x, y + h - 1, w, 1, c);
    fill(x, y, 1, h, c); fill(x + w - 1, y, 1, h, c);
}
// every pixel of the rectangle through `table` (a darkening / brightening remap of the palette)
void remap_rect(int x, int y, int w, int h, const uint8_t *table) {
    uint8_t *d = fe_tk_back();
    for (int r = std::max(y, 0); r < std::min(y + h, 200); r++)
        for (int k = std::max(x, 0); k < std::min(x + w, 320); k++) d[r * 320 + k] = table[d[r * 320 + k]];
}
void text(int x, int y, int font, uint8_t colour, const char *s) {
    FontDesc *f = fe_tk_font(font);
    if (!f->glyphs) return;
    if (font != 2) f->colour1 = colour;
    fe_tk_text(x, y, f, s);
}
int width(int font, const char *s) { FontDesc *f = fe_tk_font(font); return f->glyphs ? fe_tk_text_width(f, s) : 0; }
void text_right(int x_right, int y, int font, uint8_t colour, const char *s) { text(x_right - width(font, s), y, font, colour, s); }
void text_centre(int cx, int y, int font, uint8_t colour, const char *s) { text(cx - width(font, s) / 2, y, font, colour, s); }

uint8_t s_dark[256];                // the palette's colours at ~45 % (panels behind text)
uint8_t s_shade[256];               // ~85 % (the hovered row on the page)
void build_shade_tables() {
    const uint8_t *pal = fe_tk_palette();
    for (int i = 0; i < 256; i++) {
        const int r = pal[i * 3], g = pal[i * 3 + 1], b = pal[i * 3 + 2];
        s_dark[i] = nearest(r * 45 / 100, g * 45 / 100, b * 45 / 100);
        s_shade[i] = nearest(r * 85 / 100, g * 85 / 100, b * 85 / 100);
    }
}

