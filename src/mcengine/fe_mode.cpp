void setup_input() {
    const Input in = read_input();
    // hover
    s_su.hover = -1;
    s_su.button = 0;
    for (int i = 0; i < kItemCount; i++) {
        const Item &it = kItems[i];
        if (in.x >= it.x - 2 && in.x < it.x + it.w + 2 && in.y >= it.y - 1 && in.y < it.y + kRow - 1 && item_enabled(i)) s_su.hover = i;
    }
    if (inside(in, 0x11c, 0x12f, 0x7e, 0x91)) s_su.button = 1;
    else if (inside(in, 0x11c, 0x12f, 0x30, 0x43) || inside(in, 0xec, 0x100, 0x9c, 0xb0)) s_su.button = 2;
    else if (inside(in, kMapX, kMapX + kMapN - 1, kMapY, kMapY + kMapN - 1)) s_su.button = 3;
    if (s_su.hover >= 0) s_su.sel = s_su.hover;
    // mouse
    if (in.left || in.right) {
        const int dir = in.left ? 1 : -1;
        if (s_su.button == 1 && in.left) { setup_leave(true); return; }
        if (s_su.button == 2 && in.left) { setup_leave(false); return; }
        if (s_su.hover >= 0) {
            const int opt = kItems[s_su.hover].opt;
            if (opt == O_SEATS) {
                const int s = seat_at(in);
                if (s >= 0) s_params.match.team[s] = (uint8_t)((s_params.match.team[s] + dir + 5) % 5);
            } else {
                step_option(s_params, opt, dir);
            }
            s_params_set = true;
        }
    }
    // keyboard
    switch (in.key) {
    case 0: break;
    case MC_SC_ESC: setup_leave(false); return;
    case MC_SC_ENTER: setup_leave(true); return;
    case MC_SC_UP: case MC_SC_DOWN: case MC_SC_TAB: {
        const int dir = in.key == MC_SC_UP ? -1 : 1;
        int i = s_su.sel;
        for (int k = 0; k < kItemCount; k++) { i = (i + dir + kItemCount) % kItemCount; if (item_enabled(i) && kItems[i].opt != O_SEATS) break; }
        s_su.sel = i;
        break;
    }
    case MC_SC_LEFT: case MC_SC_RIGHT:
        if (kItems[s_su.sel].opt != O_SEED && kItems[s_su.sel].opt != O_SEATS) step_option(s_params, kItems[s_su.sel].opt, in.key == MC_SC_RIGHT ? 1 : -1);
        else if (kItems[s_su.sel].opt == O_SEED) step_option(s_params, O_SEED, 1);
        break;
    case MC_SC_BACKSPACE:
        if (kItems[s_su.sel].opt == O_SEED) s_params.seed /= 10;
        break;
    case MC_SC_R: s_params.seed = roll_seed(); break;
    default:
        if (in.key >= MC_SC_1 && in.key <= MC_SC_0 && kItems[s_su.sel].opt == O_SEED) {
            const uint32_t d = in.key == MC_SC_0 ? 0u : (uint32_t)(in.key - MC_SC_1 + 1);
            const uint64_t v = (uint64_t)s_params.seed * 10 + d;
            if (v <= 0xffffffffull) s_params.seed = (uint32_t)v;
        }
        break;
    }
}

void setup_frame() {
    switch (s_su.phase) {
    case 0:
        fe_tk_set_busy(true);
        fe_tk_cursor(-1);
        fe_tk_fade_out();
        s_su.phase = 1;
        if (fe_tk_blocked()) return;
        [[fallthrough]];
    case 1:
        setup_palette_and_background();
        fe_tk_load_fonts();
        s_su.hover = -1; s_su.button = 0; s_su.sel = 0;
        if (!s_params_set) { s_params.seed = roll_seed(); s_params_set = true; }
        preview_update(true);
        setup_draw();
        fe_tk_present();
        fe_tk_cursor(4);                                // the lobby's hand pointer (drawn for this palette)
        fe_tk_fade_in();
        s_su.phase = 2;
        if (fe_tk_blocked()) return;
        [[fallthrough]];
    case 2:
        fe_tk_clear_events(0xff);
        g_key_last = 0;
        fe_tk_set_busy(false);
        s_su.phase = 3;
        return;
    case 3:
        setup_input();
        if (s_su.phase != 3) return;                    // leaving: the fade runs
        preview_update(false);
        setup_draw();
        fe_tk_present();
        return;
    case 10:                                            // the fade out of the exit is over
        fe_tk_cursor(-1);
        std::memset(fe_tk_back(), 0, 64000);
        fe_tk_present();
        fe_tk_free_fonts();
        s_su.phase = 0;
        fe_tk_set_busy(false);
        if (s_su.ret == 4) {
            if (s_su.start) fe_lobby_set_conquest(true);
            else if (fe_lobby_conquest()) fe_lobby_set_conquest(true);     // the proposal follows the edited setup
            fe_tk_set_state(4);
        } else if (s_su.start) {
            fe_tk_start_mode();                         // fe_frame returns FE_START_MODE; the screen stays 11
        } else {
            fe_tk_set_state(2);
        }
        return;
    }
}

